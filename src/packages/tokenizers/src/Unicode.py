def in_ranges(ranges, cp):
    """Whether cp lies inside any [start, end] pair of a flat ranges list."""
    return fold(range(len(ranges) // 2), False, lambda acc, i: acc or in_pair(ranges, 2 * i, cp))


def in_pair(ranges, i, cp):
    return cp >= unwrap_or(listGet(ranges, i), 0) and cp <= unwrap_or(listGet(ranges, i + 1), -1)


def is_ascii_punctuation(cp):
    """The ASCII ranges Rust's char::is_ascii_punctuation covers."""
    return (cp >= 33 and cp <= 47) or (cp >= 58 and cp <= 64) or (cp >= 91 and cp <= 96) or (cp >= 123 and cp <= 126)


def is_punctuation(cp):
    """ASCII punctuation plus every Unicode P* category, as tokenizers splits."""
    return is_ascii_punctuation(cp) or in_ranges(PUNCT_RANGES, cp)


def is_whitespace(cp):
    """The Unicode White_Space property (Rust char::is_whitespace)."""
    return (cp >= 9 and cp <= 13) or cp == 32 or cp == 133 or cp == 160 or cp == 5760 or (cp >= 8192 and cp <= 8202) or cp == 8232 or cp == 8233 or cp == 8239 or cp == 8287 or cp == 12288


def is_control(cp):
    """The Cc Cf Cs Co categories, which clean_text drops; Tab, LF and
    CR are whitespace instead, exactly as BertNormalizer treats them."""
    if cp == 9 or cp == 10 or cp == 13:
        return False
    else:
        return in_ranges(CONTROL_RANGES, cp)


def is_chinese_char(cp):
    """The CJK ranges BertNormalizer spaces out when handle_chinese_chars."""
    return in_ranges(CHINESE_RANGES, cp)


def is_numeric(cp):
    """The Unicode Numeric property (Nd Nl No), as the Digits pre-tokenizer splits."""
    return in_ranges(NUMERIC_RANGES, cp)


def is_word_char(cp):
    """The regex \\w classes used by the Whitespace pre-tokenizer."""
    return in_ranges(WORD_RANGES, cp)


def is_mark_nonspacing(cp):
    """Combining diacritics U+0300..U+036F: the marks Latin NFD decomposes to."""
    return cp >= 768 and cp <= 879


def lowercase(cp):
    """Rust char::to_lowercase for the scripts the port covers: ASCII, Latin-1,
    Latin Extended-A, basic Greek, fullwidth Latin, and the dotted I / sharp S."""
    if cp == 304:
        return [105, 775]
    elif cp == 7838:
        return [223]
    elif cp == 376:
        return [255]
    else:
        return lower_range(cp)


def lower_range(cp):
    """The lowercase range mappings: +32 or +1 blocks, identity elsewhere."""
    if lower_plus32(cp):
        return [cp + 32]
    elif cp >= 256 and cp <= 382 and cp % 2 == 0:
        return [cp + 1]
    else:
        return [cp]


def lower_plus32(cp):
    """Whether cp sits in a block whose lowercase is cp + 32."""
    ascii_upper = cp >= 65 and cp <= 90
    latin_one = (cp >= 192 and cp <= 214) or (cp >= 216 and cp <= 222)
    greek = cp >= 913 and cp <= 937 and cp != 930
    fullwidth = cp >= 65313 and cp <= 65338
    return ascii_upper or latin_one or greek or fullwidth


def strip_lookup(cp):
    """The non-mark base of NFD(cp), or cp itself when it does not decompose."""
    table = STRIP_TABLE
    return fold(range(len(table)), cp, lambda acc, i: unwrap_or(listGet(unwrap_or(listGet(table, i), []), 1), cp) if cp == unwrap_or(listGet(unwrap_or(listGet(table, i), []), 0), -1) else acc)


def strip_base(cp):
    """The codepoints strip_accents keeps for one input char: NFD minus Mn marks."""
    if is_mark_nonspacing(cp):
        return []
    else:
        return [strip_lookup(cp)]
