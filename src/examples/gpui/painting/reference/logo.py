"""Generates ../src/logo.ospml from lyon_extra's rust_logo.rs.

lyon resolves relative, horizontal, vertical and smooth commands against the builder's current
position in f32. This replays that arithmetic in f32 (a sum of two f32 values computed in f64 and
rounded once is exactly the f32 sum) and writes absolute commands whose values are exactly those
f32 numbers, so the host's builder receives the same points the original example's builder
computed ([GPUI-HOST-SCENE]).

Usage: python3 logo.py <path to lyon_extra-1.1.0/src/rust_logo.rs>
"""
import re
import struct
import sys
from decimal import Decimal
from pathlib import Path


def f32(value):
    return struct.unpack("f", struct.pack("f", float(value)))[0]


def literal(value):
    text = repr(f32(value))
    if "e" in text:
        text = format(Decimal(f32(value)), "f")
    return text if "." in text else text + ".0"


def add(a, b):
    return (f32(a[0] + b[0]), f32(a[1] + b[1]))


def sub(a, b):
    return (f32(a[0] - b[0]), f32(a[1] - b[1]))


def main(source):
    body = Path(source).read_text()
    calls = re.findall(r"path\.(\w+)\((.*?)\);", body, re.S)
    first = current = last_ctrl = (0.0, 0.0)
    last = "end"
    steps = []
    for name, args in calls:
        numbers = [f32(n) for n in re.findall(r"-?\d+(?:\.\d+)?", args)]
        pairs = [(numbers[i], numbers[i + 1]) for i in range(0, len(numbers) - 1, 2)]
        if name == "move_to":
            to = pairs[0]
            steps.append(f"ui::MoveTo(toX = {literal(to[0])}, toY = {literal(to[1])})")
            first = current = to
            last = "begin"
        elif name == "close":
            steps.append("ui::Close")
            current = first
            last = "close"
        elif name.endswith("line_to"):
            if name == "line_to":
                to = pairs[0]
            elif name == "relative_line_to":
                to = add(current, pairs[0])
            elif name == "horizontal_line_to":
                to = (numbers[0], current[1])
            elif name == "relative_horizontal_line_to":
                to = (f32(current[0] + numbers[0]), current[1])
            elif name == "vertical_line_to":
                to = (current[0], numbers[0])
            elif name == "relative_vertical_line_to":
                to = (current[0], f32(current[1] + numbers[0]))
            else:
                raise SystemExit(f"unhandled logo command {name}")
            steps.append(f"ui::LineTo(toX = {literal(to[0])}, toY = {literal(to[1])})")
            current = to
            last = "line"
        elif name.endswith("cubic_bezier_to"):
            smooth = add(current, sub(current, last_ctrl)) if last == "cubic" else current
            if name == "cubic_bezier_to":
                a, b, to = pairs
            elif name == "relative_cubic_bezier_to":
                to, a, b = add(current, pairs[2]), add(current, pairs[0]), add(current, pairs[1])
            elif name == "smooth_cubic_bezier_to":
                a, b, to = smooth, pairs[0], pairs[1]
            elif name == "smooth_relative_cubic_bezier_to":
                a, b, to = smooth, add(current, pairs[0]), add(current, pairs[1])
            else:
                raise SystemExit(f"unhandled logo command {name}")
            steps.append(
                f"ui::CubicTo(toX = {literal(to[0])}, toY = {literal(to[1])}, ctrlAX = {literal(a[0])}, ctrlAY = {literal(a[1])}, ctrlBX = {literal(b[0])}, ctrlBY = {literal(b[1])})"
            )
            current, last_ctrl, last = to, b, "cubic"
        else:
            raise SystemExit(f"unhandled logo command {name}")
    lines = ",\n        ".join(steps)
    out = Path(__file__).resolve().parent.parent / "src" / "logo.ospml"
    out.write_text(
        "// Generated by reference/logo.py from lyon_extra 1.1.0's rust_logo.rs; do not edit.\n"
        "// Absolute f32 points, resolved exactly as lyon's SVG builder resolves them ([GPUI-HOST-SCENE]).\n"
        "namespace painting\n\n"
        "(** The Rust logo path as absolute builder commands. *)\n"
        "module Logo\n"
        "    (** Every command of the logo, in lyon's order. *)\n"
        f"    export steps () = [\n        {lines}]\n"
    )
    print(f"{len(steps)} steps -> {out}")


main(sys.argv[1])
