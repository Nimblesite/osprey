# Brace syntax belongs to the source text of an f-string, so an escape that
# decodes to a brace is that literal character and never pairs with another.
one = 1
print(f"\u007b\u007b")
print(f"\x7b\x7b")
print(f"\173\173")
print(f"\U0000007b\U0000007b")
print(f"\u007d\u007d")
print(f"\x7d\x7d")
print(f"\175\175")
print(f"\x7b\x7d")
print(f"{{")
print(f"}}")
print(f"{{}}")
print(f"{{{{")
print(f"\x7b{{")
print(f"{{\x7b")
print(f"\x7d}}")
print(f"\\{{")
print(f"\\x7b\\x7b")
print(f"{{{one}}}")
print(f"\x7b\x7b{one}\x7d\x7d")
print(f"a\x7b\x7bb{{c}}d\x7d\x7de")
print(rf"\x7b{{")
print(fr"{{\x7b}}")
print("\x7b\x7b")
print("{{")
print(r"\x7b{{")
