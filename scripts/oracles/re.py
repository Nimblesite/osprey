"""CPython oracle for @osprey/re: the Unicode range tables and match verdicts.

Writes `src/tables.py` (the embedded Unicode tables the matcher classifies
code points with) and `tests/expected.py` (the suite's expectations), both
computed from CPython 3.12's own `re` module. Run with the oracle virtualenv:
`python scripts/oracles/re.py`.

The pattern syntax and semantics being ported: literals and escapes, `.`,
classes with ranges/negation, `\\d \\w \\s \\D \\W \\S` (Unicode-aware),
`\\b \\B`, anchors `^ $ \\A \\Z`, capturing/non-capturing/named groups,
alternation, greedy and lazy quantifiers, lookahead/lookbehind (fixed width),
backreferences, the IGNORECASE/MULTILINE/DOTALL/VERBOSE flags and inline
`(?i)` etc. Positions in error messages are code point indices, exactly as
CPython reports them.

Every constant is a homogeneous list of strings: complex verdicts are encoded
with `\\x1f` (unit separator) between fields and `\\x1e` (record separator)
inside a field, since Osprey lists must have one element type. The suite
decodes them back with the same delimiters.
"""
import pathlib
import platform
import re
import unicodedata

from expected_module import write, literal

ROOT = pathlib.Path(__file__).resolve().parents[2]
SEP = "\x1f"
SEP2 = "\x1e"


def sweep_ranges(pred):
    """Maximal inclusive [lo, hi] runs of code points where pred holds."""
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append([start, cp - 1])
            start = None
    if start is not None:
        out.append([start, 0x10FFFF])
    return out


def fold_table(upper):
    """The simple single-code-point case mapping: every `[cp, folded]` pair
    where `chr(cp).upper()/lower()` is a single code point different from cp.
    U+0130's simple lowercase is U+0069 (its full lowercase is two points)."""
    pairs = []
    for cp in range(0x110000):
        ch = chr(cp)
        folded = ch.upper() if upper else ch.lower()
        if len(folded) == 1 and ord(folded) != cp:
            pairs.append([cp, ord(folded)])
    if not upper and 0x130 not in [p[0] for p in pairs]:
        pairs.append([0x130, 0x69])
    pairs.sort()
    return pairs


def write_tables():
    """Write src/tables.py: DIGITS (\\d), WORDS (\\w), SPACES (\\s), and the
    simple case fold pairs LOWER and UPPER."""
    digits = sweep_ranges(lambda cp: chr(cp).isdecimal())
    words = sweep_ranges(lambda cp: chr(cp).isalnum() or cp == 0x5F)
    spaces = sweep_ranges(lambda cp: chr(cp).isspace())
    lower = fold_table(False)
    upper = fold_table(True)
    lines = [
        "# osprey: flavor=python",
        "# Derived Unicode data; required attribution and terms: ../NOTICE.md.",
        "# osprey: namespace=re",
        "# osprey: module=Tables",
        '"""Unicode range tables the regex matcher classifies code points with.',
        "",
        f"Generated by scripts/oracles/re.py with CPython {platform.python_version()}, re {re.__version__}, Unicode {unicodedata.unidata_version}.",
        "Do not edit: rerun the oracle. DIGITS is what \\\\d matches (Unicode",
        "decimal digits, str.isdecimal), WORDS is what \\\\w matches (Unicode",
        "alphanumerics plus U+005F, str.isalnum), SPACES is what \\\\s matches",
        "(str.isspace), and LOWER/UPPER are the simple single-code-point case",
        "fold pairs used by IGNORECASE. Multi-code-point folds map to themselves.",
        '"""',
        "",
        '__all__ = ["DIGITS", "WORDS", "SPACES", "LOWER", "UPPER"]',
        "",
        "DIGITS = " + literal(digits),
        "",
        "WORDS = " + literal(words),
        "",
        "SPACES = " + literal(spaces),
        "",
        "LOWER = " + literal(lower),
        "",
        "UPPER = " + literal(upper),
        "",
    ]
    target = ROOT / "packages" / "re" / "src" / "tables.py"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))
    return target


# --- test corpus -------------------------------------------------------

TEXTS = [
    "abc", "", "a", "aaa", "aab", "b", "ac", "abcabc", "ab\ncd", "a\nb\nc",
    "hello world", "The quick brown fox", "éαβ", "日本語", "😀👍🏽", "e\u0301x",
    "a1b2c3", "   \t\n", "word-", "_x9", "12abc34", "abc123", "A1 B2",
]


def enc_match(m, ngroups, groupindex):
    """Encode a Match (or None) as a SEP-joined string with group counts."""
    if m is None:
        return "0"
    parts = ["1", str(m.start()), str(m.end()), str(m.lastindex or 0), str(ngroups)]
    for i in range(1, ngroups + 1):
        g = m.group(i)
        parts.append("0" if g is None else "1")
        parts.append("" if g is None else g)
    parts.append(str(len(groupindex)))
    for name, i in sorted(groupindex.items()):
        g = m.group(i)
        parts.append(name)
        parts.append("0" if g is None else "1")
        parts.append("" if g is None else g)
    return SEP.join(parts)


def mcase(op, pattern, flags, text):
    """One match/search/fullmatch verdict: [op, pattern, flags, text, encoded]."""
    try:
        prog = re.compile(pattern, flags)
    except re.error:
        return None
    m = prog.match(text) if op == "match" else prog.fullmatch(text) if op == "fullmatch" else prog.search(text)
    return [op, pattern, str(int(flags)), text, enc_match(m, prog.groups, prog.groupindex)]


def enc_findall(found, groups):
    """Encode a findall result: kind, count, then each element."""
    if groups == 0:
        return SEP.join(["0", str(len(found))] + list(found))
    elif groups == 1:
        return SEP.join(["1", str(len(found))] + list(found))
    else:
        rows = [SEP2.join("0" if g is None else "1" for g in row) + SEP2 + SEP2.join("" if g is None else g for g in row) for row in found]
        return SEP.join(["2", str(len(found))] + rows)


def fcase(pattern, flags, text):
    """One findall verdict: [pattern, flags, text, encoded]."""
    prog = re.compile(pattern, flags)
    found = prog.findall(text)
    return [pattern, str(int(flags)), text, enc_findall(found, prog.groups)]


def icase(pattern, flags, text):
    """One finditer verdict: [pattern, flags, text, encoded matches]."""
    prog = re.compile(pattern, flags)
    matches = [m for m in prog.finditer(text)]
    parts = [str(len(matches))]
    for m in matches:
        parts.append(enc_match(m, prog.groups, prog.groupindex))
    return [pattern, str(int(flags)), text, SEP.join(parts)]


def scase(pattern, flags, text, maxsplit):
    """One split verdict: [pattern, flags, text, maxsplit, encoded]."""
    prog = re.compile(pattern, flags)
    result = prog.split(text, maxsplit)
    parts = [str(len(result))]
    for item in result:
        parts.append("0" if item is None else "1" + SEP2 + item)
    return [pattern, str(int(flags)), text, str(maxsplit), SEP.join(parts)]


def subcase(pattern, repl, text, count, flags):
    """One sub verdict: [pattern, repl, text, count, flags, result]."""
    prog = re.compile(pattern, flags)
    return [pattern, repl, text, str(count), str(int(flags)), prog.sub(repl, text, count)]


def subncase(pattern, repl, text, count, flags):
    """One subn verdict: [pattern, repl, text, count, flags, result, n]."""
    prog = re.compile(pattern, flags)
    got, n = prog.subn(repl, text, count)
    return [pattern, repl, text, str(count), str(int(flags)), got, str(n)]


def ecase(pattern, flags):
    """One compile-error verdict: [pattern, flags, message, position]."""
    try:
        re.compile(pattern, flags)
        return None
    except re.error as e:
        return [pattern, str(int(flags)), str(e), str(e.pos)]


def main():
    write_tables()

    match_cases = []
    for pattern, flags in [
        ("abc", 0), ("", 0), ("a", 0), ("a|b", 0), ("(ab)+", 0), ("a*", 0),
        ("a+?", 0), (r"\d+", 0), (r"\w+", 0), (r"\s+", 0), ("^a", 0),
        ("a$", 0), (r"\Aa", 0), (r"a\Z", 0), (r"\bword", 0), ("a.c", 0),
        ("a.c", re.DOTALL), ("(?P<w>a)(b)?", 0), ("(a|b)(c)?", 0),
        ("(abc|def)", 0), ("a{2}", 0), ("a{2,}", 0), ("a{2,3}?", 0),
        ("[a-c]+", 0), ("[^a-c]+", 0), (r"[a-z0-9_]+", 0), ("é+", 0),
        ("αβ", 0), ("日本語", 0), ("😀+", 0), (r"\D+", 0), (r"\W+", 0),
        (r"\S+", 0), (r"\Bx", 0), ("(?i)abc", 0), ("abc", re.IGNORECASE),
        ("^b", re.MULTILINE), ("c$", re.MULTILINE), ("(?:ab)+", 0),
        ("(a)(b)(c)", 0), ("a(b(c))", 0), ("(a)?(b)?", 0), (r"(?P<d>\d)(?P=d)", 0),
        (r"(\w)\1", 0), ("(?=ab)", 0), ("(?!ab)", 0), ("(?<=ab)", 0),
        ("(?<!ab)", 0), ("(?i:AB)c", 0), (r"\x41", 0), (r"\u0041", 0),
        (r"\U0001F600", 0), (r"\t", 0), (r"\n", 0), (r"\\", 0),
    ]:
        for text in TEXTS:
            for op in ("match", "search", "fullmatch"):
                case = mcase(op, pattern, flags, text)
                if case is not None:
                    match_cases.append(case)

    findall_cases = [fcase(p, f, t) for p, f, t in [
        ("a", 0, "banana"), ("(a)", 0, "banana"), ("(a)(b)?", 0, "ab a"),
        ("(a)|b", 0, "b"), ("()", 0, "x"), (r"\d+", 0, "a1b22"),
        ("(a)?", 0, "b"), ("[^ ]+", 0, "a b c"), ("x*", 0, "abc"),
        (r"(?P<w>\w+)-", 0, "foo- bar-"), (r"(.)\1", 0, "aabb"),
    ]]
    for text in ["", "a"]:
        findall_cases.append(fcase("", 0, text))

    finditer_cases = [icase(p, f, t) for p, f, t in [
        ("a", 0, "banana"), ("(a)", 0, "banana"), (r"\w+", 0, "a b"),
        ("x*", 0, "abc"), (r"(?P<d>\d)(?P=d)", 0, "11 22 12"),
        ("a", re.IGNORECASE, "AaA"), ("^", re.MULTILINE, "a\nb"),
    ]]

    split_cases = [scase(p, f, t, mx) for p, f, t, mx in [
        ("a", 0, "banana", 0), ("(a)", 0, "banana", 0), ("a", 0, "banana", 2),
        (r"\s+", 0, "a b  c", 0), ("x*", 0, "abc", 0), ("", 0, "abc", 0),
        ("", 0, "abc", 1), (r",", 0, "a,b,c", 0), ("(,)", 0, "a,b,c", 0),
        (r"\d+", 0, "a1b22c333", 0), ("e", 0, "é", 0),
    ]]

    sub_cases = [subcase(p, r, t, c, f) for p, r, t, c, f in [
        ("a", "X", "banana", 0, 0), ("a", "X", "banana", 2, 0),
        (r"(a)(b)", r"<\2-\1>", "ab cd", 0, 0),
        (r"(?P<x>\w+)", r"[\g<x>]", "foo bar", 0, 0),
        (r"\s+", "_", "a b  c", 0, 0), ("x*", "-", "abc", 0, 0),
        ("", "-", "abc", 0, 0), (r"\.", r"\.", "a.b", 0, 0),
        (r"(z)", r"\n\t\r\\", "z z", 0, 0),
        (r"(?P<item>z)", r"\g<item>\n", "z-z", 0, 0),
    ]]

    subn_cases = [subncase(p, r, t, c, f) for p, r, t, c, f in [
        ("a", "X", "banana", 0, 0), ("a", "X", "banana", 2, 0),
        (r"(a)", r"<\1>", "bac", 0, 0), (r"\d", "#", "a1b2c3", 0, 0),
        ("z", r"\r\t\n\\", "z z", 1, 0),
    ]]

    escape_cases = [[t, re.escape(t)] for t in [
        "", "abc", "a.b*c", "()[]{}", "\\", "a+b?c", "é日本語", "-",
    ]]

    error_cases = [c for c in [
        ecase("*a", 0), ecase("a**", 0), ecase("a{2,1}", 0), ecase("a{", 0),
        ecase("(abc", 0), ecase("abc)", 0), ecase(r"\q", 0), ecase("[abc", 0),
        ecase("[z-a]", 0), ecase(r"[a-\d]", 0), ecase(r"(?P<x>a)(?P<x>b)", 0),
        ecase(r"(?P=unknown)", 0), ecase(r"\8", 0), ecase(r"(?P<1>a)", 0),
        ecase(r"(?P<x", 0), ecase(r"(?P=", 0), ecase(r"(?<x>a)", 0),
        ecase(r"(?i", 0), ecase(r"\1", 0), ecase(r"\x4", 0),
        ecase("a{3,2}", 0),
    ] if c is not None]

    write(
        "re",
        "CPython re match/search/fullmatch/findall/finditer/split/sub/subn/escape "
        "verdicts over the pattern corpus, string-encoded.",
        {"re": re.__version__},
        {
            "MATCH": match_cases,
            "FINDALL": findall_cases,
            "FINDITER": finditer_cases,
            "SPLIT": split_cases,
            "SUB": sub_cases,
            "SUBN": subn_cases,
            "ESCAPE": escape_cases,
            "ERRORS": error_cases,
        },
    )


if __name__ == "__main__":
    main()
