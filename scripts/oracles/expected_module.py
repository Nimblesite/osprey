"""Writes a port's `tests/expected.py`: the Python-flavor constants module its suite
compares against ([PORT-TEST-ORACLE], docs/specs/ecosystem/0043-PythonFlavorPorts.md).

Every oracle under scripts/oracles/ computes its cases with the real CPython package and
hands them to `write`, so all expected modules share one header, one provenance line and
one literal encoding. Values are ints, floats, bools, strings and (nested) lists of them.
The flavor has no literal for a non-finite float, so a constant that holds one has EVERY
float in it written as its repr string ("inf", "-inf", "nan", "1.5"); its type is then a
list of strings throughout, and the suite decodes each with `testing.Check.float_of`.
"""
import math
import json
import pathlib
import platform

ROOT = pathlib.Path(__file__).resolve().parents[2]


def non_finite(value):
    """Whether `value` holds a NaN or an infinity anywhere."""
    if isinstance(value, float):
        return not math.isfinite(value)
    if isinstance(value, (list, tuple)):
        return any(non_finite(v) for v in value)
    return False


def literal(value, floats_as_text=False):
    """`value` as Python-flavor source text."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, float):
        return literal(repr(value)) if floats_as_text else repr(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(literal(v, floats_as_text) for v in value) + "]"
    raise TypeError(f"no Python-flavor literal for {type(value).__name__}")


def write(package, summary, versions, constants, docs=None):
    """Write packages/<package>/tests/expected.py holding `constants` (name -> value).

    `versions` maps each oracle package name to its version string, recorded with the
    CPython version in the module docstring so a regenerated module states its source.
    `docs` maps a constant's name to its one-line documentation; every constant is an
    exported value and gets a PEP 257 attribute docstring, the given one or a default
    naming the oracle, so the flavor's undocumented-export warning never fires.
    """
    provenance = ", ".join(f"{name} {version}" for name, version in sorted(versions.items()))
    lines = [
        "# osprey: flavor=python",
        f"# osprey: namespace={package}_expected",
        "# osprey: module=Expected",
        f'"""{summary}',
        "",
        f"Generated by scripts/oracles/{package}.py with CPython {platform.python_version()} and {provenance}.",
        'Do not edit: rerun the oracle."""',
        "",
        "__all__ = [" + ", ".join(f'"{name}"' for name in constants) + "]",
        "",
    ]
    for name, value in constants.items():
        doc = (docs or {}).get(name, f"Oracle value `{name}`, computed by scripts/oracles/{package}.py.")
        lines += [f"{name} = {literal(value, non_finite(value))}", f'"""{doc}"""']
    target = ROOT / "packages" / package / "tests" / "expected.py"
    target.write_text("\n".join(lines) + "\n")
    return target
