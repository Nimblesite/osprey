const base = require('../tree-sitter-osprey/grammar');
const commaList = rule => seq(rule, repeat(seq(',', rule)), optional(','));
const body = $ => choice($.expression, $.block, $.assignment);
const member = ($, target) => prec.left(11, seq(field('target', target), '.', field('member', $.identifier)));
const index = ($, target) => prec.left(11, seq(field('target', target), token.immediate('['), $.expression, ']'));
const BRACKETS = {'(': '_open_paren', ')': '_close_paren', '[': '_open_list', ']': '_close_list', '{': '_open_record', '}': '_close_record', '=>': '_arrow'};
function nativeTokens(rule, $) {
  if (!rule || typeof rule !== 'object') return rule;
  if (rule instanceof RegExp) return rule;
  if (rule.type === 'IMMEDIATE_TOKEN' || rule.type === 'TOKEN') return rule;
  if (rule.type === 'SEQ' && rule.members.some(child => child.type === 'IMMEDIATE_TOKEN' && child.content?.value === '['))
    return {...rule, members: rule.members.map(child => child.type === 'STRING' && child.value === ']' ? child : nativeTokens(child, $))};
  if (rule.type === 'STRING' && BRACKETS[rule.value]) return alias($[BRACKETS[rule.value]], rule.value);
  return Object.fromEntries(Object.entries(rule).map(([key, value]) => [key,
    Array.isArray(value) ? value.map(child => nativeTokens(child, $)) : nativeTokens(value, $)]));
}
function nativeRules(rules) {
  return Object.fromEntries([...new Set([...Object.keys(base.grammar?.rules ?? {}), ...Object.keys(rules)])].map(name =>
    [name, ($, previous) => nativeTokens(rules[name] ? rules[name]($, previous) : previous, $)]));
}

// Implements [FLAVOR-ML-LAYOUT], retaining native source coordinates.
module.exports = grammar(base, {
  name: 'osprey_ml',
  extras: $ => [/[ \t\r]/, $.line_comment, $.doc_comment, $.block_comment, $._interpolation_space, $._soft_newline],
  externals: ($, previous) => previous.concat([$._newline, $._indent, $._dedent,
    $._open_paren, $._close_paren, $._open_list, $._close_list,
    $._open_record, $._close_record, $._arrow, $._soft_newline, $.block_comment, $._negative_gap]),
  conflicts: ($, previous) => previous.concat([
    [$.function_declaration, $.primary_expression], [$.parameter, $.primary_expression],
    [$.ml_parameters, $.primary_expression], [$.type_constructor, $.call_expression],
    [$.function_declaration, $.pattern], [$.pattern, $.call_expression],
    [$.primary_expression, $.type_constructor, $.ml_signature],
    [$.function_declaration, $.primary_expression, $.type_constructor],
    [$.assignment, $.ternary_expression],
    [$.type_declaration, $._type],
    [$.type_parameter, $.type_identifier],
    [$.expression, $.ml_postfix],
    [$.type_constructor, $._application_atom],
    [$.ternary_expression, $.field_assignment],
  ]),
  rules: nativeRules({
    source_file: $ => seq(optional($.inner_doc_comment), repeat(choice($._newline, $.statement))),
    statement: $ => prec.right(seq(choice(
      $.import_statement, $.namespace_declaration, $.function_declaration,
      $.let_declaration, $.assignment, $.extern_declaration, $.type_declaration,
      $.effect_declaration, $.module_declaration, $.signature_declaration,
      $.expression_statement, $.ml_signature, $.export_declaration, $.opaque_declaration,
    ), $._statement_break)),
    function_declaration: $ => seq(field('name', $.identifier),
      optional(field('parameters', $.ml_parameters)), '=', field('body', body($))),
    ml_parameters: $ => repeat1(choice($.parameter, $.tuple_parameters, $.integer, $.float,
      $.string, $.boolean, $.list_pattern, $.structural_pattern, $.ml_parenthesized_pattern)),
    ml_parenthesized_pattern: $ => seq('(', choice($.ml_constructor_pattern,
      $.integer, $.float, $.string, $.boolean), ')'),
    tuple_parameters: $ => seq('(', optional(commaList($.parameter)), ')'),
    let_declaration: $ => seq('mut', field('name', $.identifier), '=', field('value', body($))),
    type_declaration: $ => seq('type', $.identifier, repeat($.type_parameter), '=',
      choice($.ml_type_body, $.record_type, $.union_type, $.type_alias), optional($.type_validation)),
    ml_type_body: $ => seq($._indent, repeat1(choice(seq($.field_declaration, $._statement_break),
      seq($.ml_variant, $._statement_break), $._newline)), $._dedent),
    _constructor_identifier: $ => token(prec(1, /[A-Z][a-zA-Z0-9_]*/)),
    ml_variant: $ => seq(alias($._constructor_identifier, $.identifier), optional($.ml_type_body)),
    variant: $ => prec.right(seq(alias($._constructor_identifier, $.identifier), repeat($._ml_type_atom),
      optional(seq('(', commaList($.field_declaration), ')')))),
    field_declaration: $ => seq($.identifier, ':', $._type, optional($.ml_effect_row)),
    assignment: $ => seq(field('name', $.identifier), ':=', field('value', $.expression)),
    ml_signature: $ => prec.right(seq($.identifier,
      optional(seq(token.immediate('<'), $.type_parameter_list, '>')), ':', $._type, optional($.ml_effect_row))),
    ml_effect_row: $ => prec.right(seq('!', choice(seq('[', optional(commaList($.effect_ref)), ']'), commaList($.effect_ref)))),
    block: $ => seq($._indent, optional($.inner_doc_comment), repeat1(choice($._newline, $.statement)), $._dedent),
    expression_statement: $ => $.expression,
    import_statement: $ => seq('import', $.import_target, optional(seq('as', $.identifier)), optional($.import_projection)),
    import_projection: $ => seq($._indent, repeat1(seq($.import_member, optional($._newline))), $._dedent),
    namespace_declaration: $ => seq('namespace', $.namespace_name, optional($.block)),
    extern_declaration: $ => seq('extern', $.identifier, repeat($.tuple_parameters), '->', $._type),
    effect_declaration: $ => seq(optional($.static_stage), 'effect', $.identifier,
      repeat($.type_parameter), $._indent,
      repeat1(choice($.operation_declaration, $._newline)), $._dedent),
    operation_declaration: $ => seq(optional($.operation_mode), optional($.multiplicity),
      optional($.replayable), choice($.identifier, alias($.operation_mode, $.identifier),
        alias($.multiplicity, $.identifier), alias($.replayable, $.identifier)), ':', $._type, $._statement_break),
    module_declaration: $ => seq(choice('module', 'state'), $.symbol_path,
      optional($.signature_ascription), $.block),
    signature_declaration: $ => seq('signature', $.symbol_path, $.ml_signature_body),
    ml_signature_body: $ => seq($._indent, repeat1(choice($.ml_signature, $.signature_type,
      $.effect_declaration, $.signature_module, $._newline)), $._dedent),
    signature_type: $ => prec.right(seq(optional('opaque'), 'type', $.identifier, repeat($.type_parameter),
      optional(seq('=', choice($.ml_type_body, $.type_alias))))),
    signature_module: $ => seq('module', $.symbol_path, $.signature_ascription),
    export_declaration: $ => seq('export', choice($.function_declaration,
      $.type_declaration, $.effect_declaration, $.module_declaration, $.ml_signature, $.opaque_declaration)),
    opaque_declaration: $ => seq('opaque', $.type_declaration),
    expression: $ => choice($.match_expression, $.handler_expression,
      $.handler_value_expression, $.kernel_expression, $.select_expression,
      $.binary_expression, $.unary_expression, $.lambda_expression,
      $.pipe_expression, $.call_expression, $.field_access, $.index_expression, $.primary_expression),
    match_expression: $ => prec.right(seq('match', field('value', $.expression), $._indent,
      repeat1(choice($.match_arm, $._newline)), $._dedent)),
    match_arm: $ => seq(optional('|'), field('pattern', $.pattern), '=>', field('body', body($))),
    lambda_expression: $ => prec.right(seq('\\', optional($.ml_parameters), '=>', field('body', body($)))),
    handler_expression: $ => seq('handle', optional($.static_stage),
      choice($.qualified_path, $.identifier), optional($.type_arguments), $.handler_body),
    handler_value_expression: $ => prec.right(seq('handler', optional($.static_stage),
      choice($.qualified_path, $.identifier), optional($.type_arguments), $.handler_body)),
    handler_body: $ => seq($._indent,
      repeat1(choice($.handler_arm, $.handler_return, $.handler_finally, $._newline)), $._dedent),
    handler_arm: $ => seq(field('operation', $.identifier), optional($.ml_parameters), '=>', field('body', body($))),
    handler_return: $ => seq('return', $.identifier, '=>', field('body', body($))),
    handler_finally: $ => seq('finally', '=>', field('body', body($))),
    call_expression: $ => choice(
      prec.dynamic(1, prec.left(10, seq(field('callee', choice($.qualified_path, $.identifier)),
        token.immediate('<'), $.type_list, '>', field('argument', $.ml_argument)))),
      prec.left(10, seq(field('callee', choice($.call_expression, $.ml_postfix)), field('argument', $.ml_argument)))),
    ml_postfix: $ => choice($.field_access, $.index_expression, $.primary_expression),
    field_access: $ => member($, $.ml_postfix),
    index_expression: $ => index($, $.ml_postfix),
    binary_expression: ($, previous) => choice(previous,
      prec.right(1, seq(field('left', $.expression), field('operator', '?:'), field('right', $.expression)))),
    pipe_expression: $ => prec.left(8, seq(field('left', $.expression), '|>', field('right', $.expression))),
    unary_expression: $ => prec.right(9, seq(field('operator', choice('-', '!')), field('operand', $.expression))),
    ml_argument: $ => choice($.negative_literal_argument, alias($._application_atom, $.primary_expression),
      alias(member($, $.ml_argument), $.field_access), alias(index($, $.ml_argument), $.index_expression)),
    _application_atom: $ => choice($.type_constructor, $.update_expression, $.object_literal,
      $.literal, $.qualified_path, $.identifier, $.parenthesized_expression),
    negative_literal_argument: $ => seq($._negative_gap, field('operator', '-'),
      choice(alias(token.immediate(/[0-9]+\.[0-9]+/), $.float), alias(token.immediate(/[0-9]+/), $.integer))),
    primary_expression: $ => choice($.spawn_expression, $.yield_expression, $.perform_expression,
      $.mask_expression, $.instance_expression, $.resume_expression, $.type_constructor,
      $.await_expression, $.send_expression, $.recv_expression,
      $.update_expression, $.object_literal, $.literal,
      $.qualified_path, $.identifier, $.parenthesized_expression),
    await_expression: $ => seq('await', $.ml_postfix),
    send_expression: $ => seq('send', $.ml_postfix, $.ml_postfix),
    recv_expression: $ => seq('recv', $.ml_postfix),
    yield_expression: $ => prec.right(seq('yield', optional($.ml_postfix))),
    spawn_expression: $ => prec.right(seq('spawn', body($))),
    select_expression: $ => seq('select', $._indent, repeat1(choice($.match_arm, $._newline)), $._dedent),
    kernel_expression: $ => prec.right(seq('kernel', $._indent,
      repeat1(choice($.kernel_arm, $._newline)), $._dedent, optional($._newline), 'in', body($))),
    kernel_arm: $ => seq($.identifier, $.identifier, optional($.ml_parameters), '=>', body($)),
    parenthesized_expression: $ => seq('(', optional(commaList($.expression)), ')'),
    perform_expression: $ => prec.right(8, seq('perform', choice($.qualified_path, $.identifier),
      optional($.type_arguments), '.', $.identifier, repeat($.ml_argument))),
    resume_expression: $ => prec.right(8, seq('resume', choice($.ml_postfix, $.block, $.match_expression))),
    type_constructor: $ => prec.dynamic(1, seq(choice($.qualified_path, $.identifier),
      optional(seq(token.immediate('<'), $.type_list, '>')), '(', $.field_assignments, ')')),
    field_assignment: $ => seq(field('name', $.identifier), '=', field('value', $.expression)),
    field_assignments: $ => prec.right(commaList($.field_assignment)),
    update_expression: $ => seq($.identifier, 'with', $.field_assignments),
    named_argument: $ => $.field_assignment,
    list_literal: $ => seq('[', optional(commaList($.expression)), ']'),
    map_literal: $ => seq('[', choice('=>', commaList($.map_entry)), ']'),
    map_entry: $ => seq(field('key', $.expression), '=>', field('value', $.expression)),
    pattern: ($, previous) => choice(previous, $.ml_constructor_pattern),
    ml_constructor_pattern: $ => prec.right(seq(choice($.qualified_path,
      alias($._constructor_identifier, $.identifier)), repeat(choice($.identifier, '_')))),
    _type: $ => choice($.function_type, $._ml_type_term),
    _ml_type_term: $ => choice($.ml_type_application, $._ml_type_atom),
    _ml_type_atom: $ => choice($.tuple_type, $.generic_type, $.type_identifier),
    ml_type_application: $ => prec.right(2, seq($.type_identifier, repeat1(prec.right(3, $._ml_type_atom)))),
    function_type: $ => prec.right(1, seq($._ml_type_term, choice('->', '=>'), $._type)),
    tuple_type: $ => seq('(', commaList($._type), ')'),
    doc_comment: $ => token(seq('(**', /([^*]|\*+[^*)])*\*+/ , ')')),
    inner_doc_comment: $ => token(prec(1, seq('//!', /[^\r\n]*/,
      repeat(seq(/\r?\n/, /[ \t]*/, '//!', /[^\r\n]*/))))),
  }),
});
